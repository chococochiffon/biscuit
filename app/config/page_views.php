<?php

return [

    /*
    |--------------------------------------------------------------------------
    | chococo のサーバーとの共有の鍵
    |--------------------------------------------------------------------------
    |
    | PV は chococo のサーバーが、閲覧者の IP アドレス・User-Agent・訪問者の識別子を付けて
    | POST /api/page-views へ中継する。リクエストの X-Page-View-Key がこの値と一致するときだけ受け付ける
    | (未設定なら PV を記録しない)。chococo の NUXT_PAGE_VIEW_KEY と同じ値にする。
    |
    */

    'forward_key' => env('PAGE_VIEW_FORWARD_KEY'),

    /*
    |--------------------------------------------------------------------------
    | 重複アクセスの除外
    |--------------------------------------------------------------------------
    |
    | 同じ訪問者が同じパスをこの秒数以内にもう一度表示したときは PV に数えない。
    | 0 なら除外せず、リロードも 1 PV として数える。
    |
    */

    'duplicate_window_seconds' => (int) env('PAGE_VIEW_DUPLICATE_WINDOW_SECONDS', 0),

    /*
    |--------------------------------------------------------------------------
    | 記録しない User-Agent(Bot の除外)
    |--------------------------------------------------------------------------
    |
    | User-Agent がこの正規表現のどれかに一致するアクセスは PV に数えない(例: '/googlebot/i'、'/bingbot/i')。
    | 初期値は空で、すべて記録する。
    |
    */

    'excluded_user_agents' => [],

    /*
    |--------------------------------------------------------------------------
    | 人気コンテンツのランキングの件数
    |--------------------------------------------------------------------------
    */

    'ranking_limit' => (int) env('PAGE_VIEW_RANKING_LIMIT', 20),

];
